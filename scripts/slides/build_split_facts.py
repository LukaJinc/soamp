"""
Writes the numbers the "Splits" and "Summary" slides quote, straight from the
committed split artifacts, so they can never drift from the split the
experiments actually use:

  presentations/generated/split_table.tex   per-bucket rows of the final-design table
  presentations/generated/split_facts.tex   \\newcommand macros (cluster stats,
                                            balance, leakage measurement)

Inputs: data/peptide_split.csv + .json (pipeline/splitting/01_build_peptide_split.py)
and data/mic_classification_dataset.csv.

Leakage measurement: for every test peptide, the highest Morgan/ECFP (r=2,
2048-bit) Tanimoto similarity to any train peptide; reported is the share with
a >= 0.9 neighbour, for the committed cluster split and for random splits of
the same size (mean over 3 seeds) as the reference.

  python scripts/slides/build_split_facts.py
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd
from rdkit import Chem, DataStructs
from rdkit.Chem import rdFingerprintGenerator

REPO_ROOT = Path(__file__).resolve().parents[2]
DATA = REPO_ROOT / "data"
OUT = REPO_ROOT / "presentations" / "generated"
LEAK_THRESHOLD = 0.9
RANDOM_SEEDS = (0, 1, 2)
BUCKET_ORDER = ["test", "fold_0", "fold_1", "fold_2", "fold_3", "fold_4"]


def bucket_names(split: pd.DataFrame) -> pd.Series:
    fold = split["fold_id"].astype("Int64").astype(str)
    return split["split"].where(split["split"] == "test", "fold " + fold)


def max_similarity_share(fps: list, test_mask: np.ndarray, threshold: float) -> float:
    train = [f for f, m in zip(fps, test_mask) if not m]
    maxima = [
        max(DataStructs.BulkTanimotoSimilarity(f, train))
        for f, m in zip(fps, test_mask) if m
    ]
    return float((np.asarray(maxima) >= threshold).mean())


def main() -> None:
    split = pd.read_csv(DATA / "peptide_split.csv")
    sidecar = json.load(open(DATA / "peptide_split.json"))
    records = pd.read_csv(DATA / "mic_classification_dataset.csv")
    records["is_active"] = (records["label"] == "active").astype(int)
    records["has_noncanonical"] = records["has_noncanonical"].astype(str) == "True"
    split["bucket"] = bucket_names(split)
    records = records.merge(split[["peptide_id", "bucket"]], on="peptide_id", how="left")
    assert records["bucket"].notna().all(), "records without a split bucket"

    dataset_active = records["is_active"].mean()
    dataset_nc = records["has_noncanonical"].mean()

    rows, deviations = [], []
    order = ["test"] + [f"fold {i}" for i in range(5)]
    for bucket in order:
        part = records[records["bucket"] == bucket]
        active, nc = part["is_active"].mean(), part["has_noncanonical"].mean()
        deviations += [abs(active - dataset_active), abs(nc - dataset_nc)]
        rows.append(
            f"{bucket} & {part['peptide_id'].nunique():,} & {len(part):,} & "
            f"{100 * active:.1f} & {100 * nc:.1f} \\\\"
        )
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "split_table.tex").write_text(
        "% generated by scripts/slides/build_split_facts.py -- do not edit by hand\n"
        "\\setlength{\\tabcolsep}{4pt}\n\\begin{tabular}{@{}l r r r r@{}}\n\\toprule\n"
        "\\textbf{split} & \\textbf{peptides} & \\textbf{pairs} & \\textbf{\\% active} "
        "& \\textbf{\\% non-can.} \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\midrule\n"
        f"\\textbf{{all}} & {records['peptide_id'].nunique():,} & {len(records):,} & "
        f"{100 * dataset_active:.1f} & {100 * dataset_nc:.1f} \\\\\n"
        "\\bottomrule\n\\end{tabular}\n"
    )

    sizes = split["community"].value_counts()
    unique = records.drop_duplicates("peptide_id")[["peptide_id", "smiles"]].merge(
        split[["peptide_id", "split"]], on="peptide_id"
    )
    generator = rdFingerprintGenerator.GetMorganGenerator(radius=2, fpSize=2048)
    fps = [generator.GetFingerprint(Chem.MolFromSmiles(s)) for s in unique["smiles"]]
    test_mask = (unique["split"] == "test").to_numpy()
    cluster_leak = max_similarity_share(fps, test_mask, LEAK_THRESHOLD)
    random_leaks = []
    for seed in RANDOM_SEEDS:
        mask = np.zeros(len(unique), dtype=bool)
        mask[np.random.default_rng(seed).choice(len(unique), int(test_mask.sum()), replace=False)] = True
        random_leaks.append(max_similarity_share(fps, mask, LEAK_THRESHOLD))

    cross = sidecar.get("cross_bucket_edges", {})
    facts = {
        "splitClusters": f"{int(sizes.size):,}",
        "splitLargestPct": f"{100 * sidecar['largest_cluster_fraction']:.1f}",
        "splitSingletons": f"{int((sizes == 1).sum()):,}",
        "splitHardLinkPairs": f"{sidecar.get('n_hard_links', 0):,}",
        "splitHardLinkCross": str(cross.get("hard_links", "n/a")),
        "splitActivePct": f"{100 * dataset_active:.1f}",
        "splitNcPct": f"{100 * dataset_nc:.1f}",
        "splitMaxDevPct": f"{100 * max(deviations):.1f}",
        "splitLeakThreshold": f"{LEAK_THRESHOLD:.1f}",
        "splitLeakClusterPct": f"{100 * cluster_leak:.1f}",
        "splitLeakRandomPct": f"{100 * float(np.mean(random_leaks)):.0f}",
    }
    (OUT / "split_facts.tex").write_text(
        "% generated by scripts/slides/build_split_facts.py -- do not edit by hand\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in facts.items())
    )
    print(json.dumps(facts, indent=1))
    print((OUT / "split_table.tex").read_text())


if __name__ == "__main__":
    main()
